"""Generate paper/results.tex (macros + tables) and docs/results.md from the measured results.

Every number in the paper and the Devpost description comes through this script.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "attacks" / "results"
A = json.loads((RES / "attacks.json").read_text())
T = json.loads((RES / "timing_rust.json").read_text())
B = json.loads((RES / "bench.json").read_text())

m = {}  # macro name -> value


def pct(x):
    return "--" if x is None else f"{100 * x:.1f}\\%"


def pct_md(x):
    return "–" if x is None else f"{100 * x:.1f}%"


# E1
e1 = A["E1_perfect_secrecy"]
m["EonePrimes"] = ", ".join(f"$(p,t)=({r['p']},{r['t']})$" for r in e1["toy_cases"])
m["EoneAllIdentical"] = "Yes" if all(r["identical_for_all_secrets"] for r in e1["toy_cases"]) and e1["tags_independent_of_secret_p31"] else "NO"
# E2
e2 = A["E2_uniformity"]
m["EtwoN"] = f"{e2['sharings']:,}".replace(",", "{,}")
m["EtwoBins"] = str(e2["bins"])
m["EtwoP"] = ", ".join(f"{x:.3f}" for x in e2["chi2_pvalues_shares_1_2_5"])
m["EtwoMIbiased"] = f"{e2['exact_MI_bits_biased_coeffs_control']:.4f}"
m["EtwoMIuniform"] = f"{e2['exact_MI_bits_uniform_coeffs']:.1f}"
# E3
e3 = A["E3_collusion_z3"]
s3, mg = e3["saksi_toy"], e3["mignotte_control"]
m["EthreeSaksiCand"] = str(s3["candidate_secrets"])
m["EthreeSaksiSpace"] = str(s3["secret_space"])
m["EthreeSaksiBits"] = f"{s3['bits_leaked']:.2f}"
m["EthreeMigCand"] = str(mg["candidate_secrets"])
m["EthreeMigSpace"] = f"{mg['secret_space']:,}".replace(",", "{,}")
m["EthreeMigBits"] = f"{mg['bits_leaked']:.2f}"
# E4
e4 = A["E4_forgery_rate"]
m["EfourTrials"] = f"{e4['trials_per_p']:,}".replace(",", "{,}")
worst = max(abs(r["empirical"] - r["theory_1_over_p"]) for r in e4["rows"])
m["EfourMaxDev"] = f"{worst:.4f}"
# E5
e5 = A["E5_active_attacks"]["rows"]
# E6/E7/E8
e6, e7, e8 = A["E6_rust_core"], A["E7_fuzz_rust"], A["E8_python_reference_timing"]
m["EfiveBitflip"] = pct(next(r for r in e5 if r["attack"].startswith("bit flip"))["control_wrong_key_rate"])
m["EsixTrials"] = str(e6["trials"])
m["EsixCorrect"] = pct(e6["correct_key_rate"])
m["EsixWrong"] = pct(e6["wrong_key_rate"])
m["EsixNamed"] = pct(e6["cheater_named_rate"])
m["EsevenN"] = f"{e7['mutated_bundles']:,}".replace(",", "{,}")
m["EsevenCrash"] = str(e7["crashes"])
m["EsevenWrong"] = str(e7["wrong_key_returned"])
m["EeightT"] = f"{abs(e8['t']):.1f}"
m["EeightN"] = f"{e8['samples']:,}".replace(",", "{,}")
# bench
m["BenchMul"] = f"{B['mul_ns']:.1f}"
m["BenchInv"] = f"{B['inv_ns'] / 1000:.2f}"
m["BenchDeal"] = f"{B['deal_5_3_32B_us']:.1f}"
m["BenchRec"] = f"{B['reconstruct_5_3_us']:.1f}"
m["BenchKeyless"] = f"{B['keyless_decode_5_3_1err_us']:.1f}"
# timing
core = [r for r in T if not r["op"].startswith("CONTROL")]
ctrl = [r for r in T if r["op"].startswith("CONTROL")]
m["TimingMaxCore"] = f"{max(abs(r['t']) for r in core):.2f}"
m["TimingMinCtrl"] = f"{min(abs(r['t']) for r in ctrl):.0f}"
m["TimingSamples"] = f"{max(r['samples'] for r in T):,}".replace(",", "{,}")

out = ["% AUTO-GENERATED by gen_results.py from attacks/results/*.json -- do not edit"]
for k, v in m.items():
    out.append(f"\\newcommand{{\\{k}}}{{{v}}}")

# E5 table
lines = [r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{5.0cm}rccc@{}}", r"\toprule",
         r"Attack & Trials & Control fooled & SAKSI wrong key & SAKSI names cheater \\", r"\midrule"]
for r in e5:
    if "control_tag_layer_bypassed_rate" in r:
        continue
    if r["attack"].startswith("3 of 5"):
        continue
    lines.append(f"{r['attack'].replace('Tompa-Woll','Tompa--Woll')} & {r['trials']} & {pct(r.get('control_wrong_key_rate'))} & "
                 f"{pct(r.get('saksi_wrong_key_rate'))} & {pct(r.get('saksi_cheater_named_rate'))} \\\\")
lines += [r"\bottomrule", r"\end{tabular}"]
(ROOT / "paper" / "table_e5.tex").write_text("\n".join(lines) + "\n")

rush = next(r for r in e5 if "control_tag_layer_bypassed_rate" in r)
bound = next(r for r in e5 if r["attack"].startswith("3 of 5"))
out.append(f"\\newcommand{{\\RushTrials}}{{{rush['trials']}}}")
out.append(f"\\newcommand{{\\RushOneRound}}{{{pct(rush['control_tag_layer_bypassed_rate'])}}}")
out.append(f"\\newcommand{{\\RushSyndrome}}{{{pct(rush['control_then_caught_by_syndrome_rate'])}}}")
out.append(f"\\newcommand{{\\RushTwoRound}}{{{pct(rush['saksi_tag_layer_bypassed_rate'])}}}")
out.append(f"\\newcommand{{\\BoundWrong}}{{{pct(bound['saksi_wrong_key_rate'])}}}")
out.append(f"\\newcommand{{\\BoundClosed}}{{{pct(bound.get('saksi_fail_closed_rate'))}}}")
out.append(f"\\newcommand{{\\BoundTrials}}{{{bound['trials']}}}")

# timing table
tl = [r"\begin{tabular}{@{}lrrrl@{}}", r"\toprule",
      r"Operation (class A vs class B) & Samples & Mean A & Mean B & $|t|$ \\", r"\midrule"]
for r in T:
    name = r["op"].replace("CONTROL ", "\\emph{control:} ").replace("::", "::")
    tl.append(f"{name} & {r['samples']:,} & {r['mean_fixed']:.1f} & {r['mean_random']:.1f} & {abs(r['t']):.2f} \\\\".replace(",", "{,}", 1))
tl += [r"\bottomrule", r"\end{tabular}"]
(ROOT / "paper" / "table_timing.tex").write_text("\n".join(tl).replace("_", r"\_") + "\n")
(ROOT / "paper" / "results.tex").write_text("\n".join(out) + "\n")

# ---------------- markdown tables for Devpost
md = ["| Attack (real parameters, p = 2¹²⁷−1, n = 5, t = 3) | Trials | Plain Shamir returns wrong key | SAKSI returns wrong key | SAKSI names the cheater |",
      "|---|---:|---:|---:|---:|"]
for r in e5:
    if "control_tag_layer_bypassed_rate" in r or r["attack"].startswith("3 of 5"):
        continue
    md.append(f"| {r['attack']} | {r['trials']} | {pct_md(r.get('control_wrong_key_rate'))} | "
              f"{pct_md(r.get('saksi_wrong_key_rate'))} | {pct_md(r.get('saksi_cheater_named_rate'))} |")
md.append("")
md.append("| Operation (Rust core, dudect) | Samples | \\|t\\| | Verdict (threshold 4.5) |")
md.append("|---|---:|---:|---|")
for r in T:
    md.append(f"| {r['op']} | {r['samples']:,} | {abs(r['t']):.2f} | {r['verdict']} |")
(ROOT / "docs" / "results_tables.md").write_text("\n".join(md) + "\n")
json.dump({"macros": m, "rush": rush, "bound": bound, "e6": e6, "e7": e7, "e8": e8},
          open(ROOT / "docs" / "numbers.json", "w"), indent=1)
print("ok", len(m), "macros")
